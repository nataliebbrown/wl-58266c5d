export function getKeyWord(id: string): KeyWord | undefined {
  return KEY_WORDS.find(k => k.id === id);
}

/** The same word all day; rotates daily through the list. */
export function wordOfTheDay(date = new Date()): KeyWord {
  const day = Math.floor(new Date(date.getFullYear(), date.getMonth(), date.getDate()).getTime() / 86_400_000);
  return KEY_WORDS[((day % KEY_WORDS.length) + KEY_WORDS.length) % KEY_WORDS.length];
}
